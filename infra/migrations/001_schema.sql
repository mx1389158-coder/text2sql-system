BEGIN;

CREATE TABLE regions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  parent_id BIGINT REFERENCES regions(id),
  UNIQUE (name, parent_id)
);

CREATE TABLE teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id BIGINT NOT NULL REFERENCES regions(id),
  name VARCHAR(100) NOT NULL,
  UNIQUE (region_id, name)
);

CREATE TABLE agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES teams(id),
  name VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('active', 'inactive')),
  hired_at DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id BIGINT NOT NULL REFERENCES regions(id),
  name VARCHAR(100) NOT NULL,
  registered_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE customer_addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  region_id BIGINT NOT NULL REFERENCES regions(id),
  city VARCHAR(80) NOT NULL,
  address_line VARCHAR(240) NOT NULL
);

CREATE TABLE product_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES product_categories(id),
  model_code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  list_price NUMERIC(12,2) NOT NULL CHECK (list_price >= 0),
  launched_at DATE
);

CREATE TABLE firmware_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  version VARCHAR(40) NOT NULL,
  released_at TIMESTAMPTZ NOT NULL,
  UNIQUE (product_id, version)
);

CREATE TABLE devices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  firmware_id BIGINT REFERENCES firmware_versions(id),
  serial_number VARCHAR(80) NOT NULL UNIQUE,
  activated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE device_upgrades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  from_firmware_id BIGINT REFERENCES firmware_versions(id),
  to_firmware_id BIGINT NOT NULL REFERENCES firmware_versions(id),
  upgraded_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('success', 'failed'))
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  order_no VARCHAR(40) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL CHECK (status IN ('created', 'paid', 'completed', 'cancelled')),
  ordered_at TIMESTAMPTZ NOT NULL,
  total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  status VARCHAR(20) NOT NULL CHECK (status IN ('pending', 'succeeded', 'failed')),
  paid_at TIMESTAMPTZ
);

CREATE TABLE refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id BIGINT NOT NULL REFERENCES order_items(id),
  refund_type VARCHAR(20) NOT NULL CHECK (refund_type IN ('return', 'exchange', 'refund_only')),
  status VARCHAR(20) NOT NULL CHECK (status IN ('requested', 'approved', 'rejected', 'completed')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE fault_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  category VARCHAR(80) NOT NULL,
  description TEXT NOT NULL
);

CREATE TABLE tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  fault_code_id BIGINT REFERENCES fault_codes(id),
  assigned_agent_id BIGINT REFERENCES agents(id),
  status VARCHAR(20) NOT NULL CHECK (status IN ('open', 'assigned', 'resolved', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL,
  resolved_at TIMESTAMPTZ,
  CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);

CREATE TABLE ticket_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES tickets(id),
  event_type VARCHAR(40) NOT NULL,
  from_status VARCHAR(20),
  to_status VARCHAR(20),
  occurred_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE service_visits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES tickets(id),
  agent_id BIGINT NOT NULL REFERENCES agents(id),
  started_at TIMESTAMPTZ NOT NULL,
  finished_at TIMESTAMPTZ,
  CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE satisfaction_surveys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL UNIQUE REFERENCES tickets(id),
  score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
  comment TEXT,
  submitted_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE warranties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL UNIQUE REFERENCES devices(id),
  starts_at DATE NOT NULL,
  ends_at DATE NOT NULL,
  CHECK (ends_at >= starts_at)
);

CREATE TABLE warehouses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id BIGINT NOT NULL REFERENCES regions(id),
  name VARCHAR(100) NOT NULL,
  UNIQUE (region_id, name)
);

CREATE TABLE inventory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL CHECK (quantity >= 0),
  updated_at TIMESTAMPTZ NOT NULL,
  UNIQUE (warehouse_id, product_id)
);

CREATE TABLE shipments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  address_id BIGINT NOT NULL REFERENCES customer_addresses(id),
  status VARCHAR(20) NOT NULL CHECK (status IN ('pending', 'shipped', 'delivered', 'returned')),
  shipped_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  CHECK (delivered_at IS NULL OR shipped_at IS NULL OR delivered_at >= shipped_at)
);

CREATE INDEX idx_orders_ordered_at ON orders(ordered_at);
CREATE INDEX idx_order_items_product ON order_items(product_id);
CREATE INDEX idx_refunds_created_at ON refunds(created_at);
CREATE INDEX idx_devices_product ON devices(product_id);
CREATE INDEX idx_upgrades_device_time ON device_upgrades(device_id, upgraded_at);
CREATE INDEX idx_tickets_device_time ON tickets(device_id, created_at);
CREATE INDEX idx_tickets_status ON tickets(status);
CREATE INDEX idx_ticket_events_ticket_time ON ticket_events(ticket_id, occurred_at);

COMMENT ON TABLE orders IS '销售订单；有效订单口径由语义目录版本化管理';
COMMENT ON TABLE tickets IS '售后工单；取消工单不得进入处理时长指标';
COMMENT ON TABLE device_upgrades IS '固件升级事件，用于升级前后效果分析';

COMMIT;

